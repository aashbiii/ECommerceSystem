CREATE TABLE users (
    id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  VARCHAR2(50)  NOT NULL UNIQUE,
    password  VARCHAR2(100) NOT NULL,
    role      VARCHAR2(20)  DEFAULT 'customer' NOT NULL
              CHECK (role IN ('admin', 'customer')),
    email     VARCHAR2(100)
);

CREATE TABLE customers (
    id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR2(100) NOT NULL,
    email    VARCHAR2(100) UNIQUE,
    phone    VARCHAR2(20),
    address  VARCHAR2(255)
);

CREATE TABLE products (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR2(100) NOT NULL,
    description  VARCHAR2(255),
    price        NUMBER(10, 2) NOT NULL CHECK (price >= 0),
    stock        NUMBER(10)    DEFAULT 0 NOT NULL CHECK (stock >= 0),
    category     VARCHAR2(50)
);

CREATE TABLE orders (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   NUMBER REFERENCES customers(id) ON DELETE SET NULL,
    order_date    DATE DEFAULT SYSDATE NOT NULL,
    total_amount  NUMBER(12, 2) NOT NULL,
    status        VARCHAR2(20) DEFAULT 'pending' NOT NULL
                  CHECK (status IN ('pending', 'processing', 'shipped', 'delivered', 'cancelled'))
);

CREATE TABLE order_items (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    NUMBER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id  NUMBER REFERENCES products(id) ON DELETE SET NULL,
    quantity    NUMBER(10)    NOT NULL CHECK (quantity > 0),
    unit_price  NUMBER(10, 2) NOT NULL
);

